/* Generates third_party/bearssl/src/ec/ec_p256_m64_comb.h: for each of the 64 nibble positions i of a
   P-256 scalar, the affine points j * 16^i * G for j = 1..15, in BearSSL's Montgomery representation.
   Built and run by tools/regen-bearssl.sh against the original ec_p256_m64.c (its static helpers). */
#define XS_P256_COMB_GEN 1
#include "ec/ec_p256_m64.c"
#include <stdio.h>

int main(void) {
    p256_jacobian B, J[15];
    p256_affine A[15];
    /* B = G, in Jacobian Montgomery coordinates: P256_Gwin[0] is 1*G */
    memcpy(B.x, P256_Gwin[0].x, sizeof B.x);
    memcpy(B.y, P256_Gwin[0].y, sizeof B.y);
    memcpy(B.z, F256_R, sizeof B.z);
    printf("/* Generated by tools/gen_p256_comb.c: P256_Gcomb[i][j-1] = j * 16^i * G (affine, Montgomery). */\n");
    printf("static const p256_affine P256_Gcomb[64][15] = {\n");
    for (int i = 0; i < 64; i++) {
        J[0] = B;
        J[1] = B; p256_double(&J[1]);
        for (int j = 2; j < 15; j++) { J[j] = J[j - 1]; p256_add(&J[j], &B); }
        window_to_affine(A, J, 15);
        printf("\t{\n");
        for (int j = 0; j < 15; j++) {
            printf("\t\t{ { 0x%016llX, 0x%016llX, 0x%016llX, 0x%016llX },\n", (unsigned long long)A[j].x[0], (unsigned long long)A[j].x[1], (unsigned long long)A[j].x[2], (unsigned long long)A[j].x[3]);
            printf("\t\t  { 0x%016llX, 0x%016llX, 0x%016llX, 0x%016llX } }%s\n", (unsigned long long)A[j].y[0], (unsigned long long)A[j].y[1], (unsigned long long)A[j].y[2], (unsigned long long)A[j].y[3], j < 14 ? "," : "");
        }
        printf("\t}%s\n", i < 63 ? "," : "");
        for (int d = 0; d < 4; d++) p256_double(&B);
    }
    printf("};\n");
    return 0;
}
